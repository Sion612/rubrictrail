export function formatAppMessage(
  template: string,
  values: Record<string, string | number> = {},
): string {
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match,
  );
}

function escapePattern(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function templateValues(template: string, message: string): Record<string, string> | null {
  const keys: string[] = [];
  let cursor = 0;
  let pattern = "^";
  for (const match of template.matchAll(/\{([A-Za-z0-9_]+)\}/g)) {
    const index = match.index ?? 0;
    pattern += escapePattern(template.slice(cursor, index));
    pattern += "([\\s\\S]+?)";
    keys.push(match[1]);
    cursor = index + match[0].length;
  }
  if (keys.length === 0) return template === message ? {} : null;
  pattern += `${escapePattern(template.slice(cursor))}$`;
  const matched = new RegExp(pattern).exec(message);
  if (!matched) return null;
  return Object.fromEntries(keys.map((key, index) => [key, matched[index + 1]]));
}

export function localizeStoredAppMessage(message: string, locale: "en" | "zh-CN"): string {
  const target = locale === "zh-CN" ? appZhCN : appEn;
  const sources = locale === "zh-CN" ? [appEn, appZhCN] : [appZhCN, appEn];
  for (const source of sources) {
    for (const key of Object.keys(appEn) as AppMessageKey[]) {
      const values = templateValues(source[key], message);
      if (values) return formatAppMessage(target[key], values);
    }
  }
  return message;
}
