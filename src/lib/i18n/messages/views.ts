export function interpolateViewMessage(
  template: string,
  values: Record<string, string | number>,
): string {
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match,
  );
}

export function localizeSystemText(text: string, locale: Locale): string {
  if (locale !== "zh-CN") return text;
  const direct = SYSTEM_TEXT_ZH_CN[text];
  if (direct) return direct;

  const evidenceTitle = /^Build evidence for (.+)$/u.exec(text);
  if (evidenceTitle) return `为“${evidenceTitle[1]}”准备依据`;

  const evidenceDescription = /^Collect, analyse and explain the material that lets a reviewer see how you meet “(.+)”\.$/u.exec(text);
  if (evidenceDescription) {
    return `收集、分析并解释材料，让评阅者清楚看到你如何满足“${evidenceDescription[1]}”。`;
  }

  const outlineLimit = /^The outline fits the (.+)-word limit$/u.exec(text);
  if (outlineLimit) return `提纲符合 ${outlineLimit[1]} 字限制`;

  const citationFormat = /^Citation formatting follows (.+)$/u.exec(text);
  if (citationFormat) return `引用格式遵循 ${citationFormat[1]}`;

  const deadlinePassed = /^The deadline has passed with (.+) hours of work remaining\.$/u.exec(text);
  if (deadlinePassed) return `截止日期已过，仍有 ${deadlinePassed[1]} 小时工作未完成。`;

  const capacity = /^The plan is (.+) hours over available capacity\. Increase to about (.+) hours per week or narrow the scope\.$/u.exec(text);
  if (capacity) return `计划超出可用容量 ${capacity[1]} 小时。请将每周投入提高到约 ${capacity[2]} 小时，或缩小范围。`;

  return text;
}
