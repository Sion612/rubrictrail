export function localizeCriterionReference(criterionId: string, locale: Locale): string {
  const sampleReference = (
    SAMPLE_CRITERION_REFERENCES as Readonly<Record<string, Readonly<Record<Locale, string>>>>
  )[criterionId];
  if (sampleReference) return sampleReference[locale];

  const ordinal = /(?:^|[-_])(\d+)$/u.exec(criterionId)?.[1];
  if (locale === "zh-CN") return ordinal ? `评分项 ${ordinal}` : "评分项";
  if (ordinal && /^criterion[-_]\d+$/u.test(criterionId)) return `Criterion ${ordinal}`;
  return criterionId
    .split(/[-_]+/u)
    .filter(Boolean)
    .map((part) => `${part.charAt(0).toUpperCase()}${part.slice(1)}`)
    .join(" ") || "Rubric criterion";
}

